import { about } from "./sections/about.ts";
import { credlyBadges } from "./sections/credly.ts";
import { header } from "./sections/header.ts";
import { leetcodeStats } from "./sections/leetcode.ts";
import { techStack } from "./sections/stack.ts";
import { timeline } from "./sections/timeline.ts";
import { typingIntro } from "./sections/typing.ts";
import type { BuildContext, GeneratedAsset, Section } from "./types.ts";

export const GENERATED_NOTICE = "<!-- Generated by pnpm build. Edit content/, not this file. -->";

/** The README sections, top to bottom. Add a section by appending its function here. */
export const sections: readonly Section[] = [
  header,
  typingIntro,
  about,
  techStack,
  leetcodeStats,
  timeline,
  credlyBadges,
];

export type RenderedReadme = {
  readonly readme: string;
  readonly assets: readonly GeneratedAsset[];
};

export function renderReadme(ctx: BuildContext): RenderedReadme {
  const outputs = sections.map((section) => section(ctx));
  const body = [GENERATED_NOTICE, ...outputs.map((o) => o.markdown.trim())].join("\n\n");
  return {
    readme: `${body}\n`,
    assets: outputs.flatMap((o) => o.assets ?? []),
  };
}
